def compress(data, window):
    """Two-byte LZ matches: 9-bit distance, 6-bit length; literal runs <=128."""
    out=bytearray(); literals=bytearray(); i=0
    def flush():
        if literals:
            out.append(len(literals)-1); out.extend(literals); literals.clear()
    while i<len(data):
        best_length=0; best_distance=0
        for distance in range(1,min(i,window)+1):
            length=0
            while length<66 and i+length<len(data) and data[i+length]==data[i+length-distance]: length+=1
            if length>best_length: best_length,best_distance=length,distance
        if best_length>=3:
            flush(); distance=best_distance-1
            out.extend([128 | ((distance>>8)<<6) | (best_length-3),distance&255]); i+=best_length
        else:
            literals.append(data[i]); i+=1
            if len(literals)==128: flush()
    flush(); return bytes(out)
def decompress(data):
    out=bytearray(); i=0
    while i<len(data):
        token=data[i]; i+=1
        if token&128:
            distance=(((token&64)<<2)|data[i])+1; i+=1
            assert distance<=len(out)
            for _ in range((token&63)+3): out.append(out[-distance])
        else:
            length=token+1; out.extend(data[i:i+length]); i+=length
    return bytes(out)
