def nums(s):
    s=re.sub(r'/\*.*?\*/|//[^\n]*','',s,flags=re.S)
    return bytes(int(x,16) for x in re.findall(r'0x([0-9a-fA-F]+)',s))
font=nums(FONT.read_text().split('= {',1)[1])
def label(im,y,s):
    x=(32-len(s)*6)//2
    for ch in s:
        for col,v in enumerate(font[ord(ch)*6:ord(ch)*6+6]):
            for b in range(8):
                if v & (1<<b): im.putpixel((x+col,y+b),1)
        x+=6
def pack(im):
    return bytes(sum(im.getpixel((x,y+b))<<b for b in range(8)) for y in range(0,im.height,8) for x in range(im.width))
def unpack(data,w,h):
    im=Image.new('1',(w,h))
    for i,v in enumerate(data):
        for b in range(8):
            if v & 1<<b: im.putpixel((i%w,(i//w)*8+b),1)
    return im
def cluster(im,letters):
    d=ImageDraw.Draw(im)
    for x,y,ch in [(12,47,letters[0]),(3,59,letters[1]),(12,59,letters[2]),(21,59,letters[3])]:
        d.rectangle((x-1,y-1,x+6,y+8),outline=1)
        for col,v in enumerate(font[ord(ch)*6:ord(ch)*6+5]):
            for b in range(7):
                if v & 1<<b: im.putpixel((x+col,y+b),1)
