def stream(name,data):
    return 'static const uint8_t PROGMEM '+name+f'[{len(data)}] = {{\n'+''.join('    '+', '.join(f'0x{v:02x}' for v in data[i:i+16])+',\n' for i in range(0,len(data),16))+'};\n'
